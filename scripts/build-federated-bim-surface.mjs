import {
  mkdir,
  mkdtemp,
  readFile,
  rm,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const ENTRY = path.join(
  ROOT,
  "packages",
  "federated-bim-surface",
  "src",
  "package-entry.mjs",
);
const OUTPUT = path.join(
  ROOT,
  "packages",
  "federated-bim-surface",
  "runtime",
  "index.mjs",
);

async function createBundle(output) {
  await mkdir(path.dirname(output), { recursive: true });
  await build({
    banner: {
      js:
        "// Generated by scripts/build-federated-bim-surface.mjs. " +
        "MPL-2.0; do not edit directly.",
    },
    bundle: true,
    entryPoints: [ENTRY],
    format: "esm",
    legalComments: "none",
    minify: false,
    outfile: output,
    platform: "neutral",
    sourcemap: false,
    target: ["es2022"],
  });
}

export async function checkFederatedBimSurfaceBundle() {
  const temporary = await mkdtemp(
    path.join(tmpdir(), "bim-explorer-federated-surface-"),
  );
  try {
    const generated = path.join(temporary, "index.mjs");
    await createBundle(generated);
    const [expected, observed] = await Promise.all([
      readFile(OUTPUT),
      readFile(generated),
    ]);
    if (!expected.equals(observed)) {
      throw new Error(
        "Federated BIM surface bundle is stale; run " +
          "npm run build:bim-surface:v0.2",
      );
    }
    process.stdout.write(
      `Federated BIM surface bundle check passed: ` +
        `${expected.byteLength} bytes\n`,
    );
  } finally {
    await rm(temporary, { force: true, recursive: true });
  }
}

async function main() {
  if (
    process.argv.length === 3 &&
    process.argv[2] === "--check"
  ) {
    await checkFederatedBimSurfaceBundle();
    return;
  }
  if (process.argv.length !== 2) {
    throw new TypeError(
      "usage: node scripts/build-federated-bim-surface.mjs " +
        "[--check]",
    );
  }
  await createBundle(OUTPUT);
  const body = await readFile(OUTPUT);
  process.stdout.write(
    `Federated BIM surface bundle built: ${body.byteLength} bytes\n`,
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await main();
}
